// Builds the runtime assets in public/ from the BusyTeX release in vendor/busytex (npm run assets:download) and
// writes public/core/runtime-manifest.json.
//
// 1. Copies the engine (busytex.js/.wasm, pipeline and worker scripts) to public/core/busytex.
// 2. Replaces BusyTeX's 87 MiB TeX Live package with one holding only the files this template needs. The engine runs
//    in Node (scripts/busytex-node.mjs) on the CVs in scripts/coverage-cvs.ts; the files it touches, minus fonts
//    and data that do not change the output, form the package. The build fails unless every CV compiles to a
//    byte-identical PDF with the trimmed package.
// 3. Lists every runtime file (engine, TeX files, fonts) in the manifest with its size and content hash, so the app
//    can show download progress and cache each file under a versioned key. Large binaries are gzipped and split
//    into parts under public/core/packs/: Cloudflare does not compress .data, .ttc or split files, and no static
//    asset may exceed 25 MiB. The service worker serves the original URLs from the app's cache.
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { appendFileSync, copyFileSync, existsSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { gzipSync, constants as zlibConstants } from "node:zlib";
import { build } from "esbuild";

const root = process.cwd();
const vendorDir = path.join(root, "vendor/busytex");
const publicDir = path.join(root, "public");
const busytexDir = path.join(publicDir, "core/busytex");
const texmfDir = path.join(publicDir, "core/texmf");
const fontsDir = path.join(publicDir, "fonts/latex");
const packDir = path.join(publicDir, "core/packs");
const manifestPath = path.join(publicDir, "core/runtime-manifest.json");

const engineFiles = ["busytex.js", "busytex.wasm", "busytex_pipeline.js", "busytex_worker.js", "busytex_biber.js", "versions.txt"];
const partSizeBytes = 8 * 1024 * 1024;
const maxAssetBytes = 25 * 1024 * 1024;
const packedExtensions = new Set([".wasm", ".data", ".ttf", ".otf", ".ttc"]);
const packThresholdBytes = 1024 * 1024;
const requiredSupplementalAssets = [
  "fontspec.cfg",
  "fontspec-luatex.sty",
  "fontspec-xetex.sty",
  "fontspec.lua",
  "fontspec.sty",
  "svgnam.def",
  "x11nam.def",
  "xcolor-2022-06-12.sty",
  "xcolor.sty"
];

function toPublicPath(filePath) {
  return `/${path.relative(publicDir, filePath).split(path.sep).join("/")}`;
}

function fromPublicPath(publicPath) {
  return path.join(publicDir, ...publicPath.slice(1).split("/"));
}

function listFiles(dir, recursive) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) return recursive ? listFiles(full, true) : [];
    return entry.name.startsWith(".") ? [] : [full];
  });
}

function findIcupkg() {
  const candidates = [process.env.ICUPKG, "icupkg", ...["icu4c", "icu4c@78", "icu4c@77"].map((name) => `/opt/homebrew/opt/${name}/sbin/icupkg`), "/usr/local/opt/icu4c/sbin/icupkg"];
  for (const candidate of candidates.filter(Boolean)) {
    try {
      execFileSync(candidate, ["-h"], { stdio: "ignore" });
      return candidate;
    } catch (error) {
      // icupkg -h exits non-zero after printing usage; only a missing binary throws ENOENT.
      if (error.code !== "ENOENT") return candidate;
    }
  }
  return null;
}

function mib(bytes) {
  return `${(bytes / 2 ** 20).toFixed(1)} MiB`;
}

function runEngine(command, engineDir, packageJs, jobsPath, ...outputs) {
  execFileSync(process.execPath, [path.join(root, "scripts/busytex-node.mjs"), command, engineDir, packageJs, jobsPath, ...outputs], {
    stdio: ["ignore", "ignore", "inherit"]
  });
  return JSON.parse(readFileSync(outputs[0], "utf8"));
}

/** BusyTeX's data package loader, without LZ4 or the IndexedDB copy: the app caches the download itself. */
function packageLoader(dirs, files, providesComments) {
  return `${providesComments}
// TeX Live files for CV Forge's template, generated by scripts/build-runtime-assets.mjs from BusyTeX's texlive-basic.
var Module = typeof BusytexPipeline != 'undefined' ? BusytexPipeline : {};
(() => {
  // BusyTeX's whole directory tree, empty directories included, as [parent, name] pairs.
  var dirs = ${JSON.stringify(dirs)};
  var files = ${JSON.stringify(files)};
  var dependency = 'datafile_texlive-basic.data';

  async function fetchPackage() {
    var name = Module['locateFile'] ? Module['locateFile']('texlive-basic.data', '') : 'texlive-basic.data';
    if (globalThis.process?.versions?.node) return new Uint8Array(require('fs').readFileSync(name)).buffer;
    var response = await fetch(name);
    if (!response.ok) throw new Error(response.status + ': ' + response.url);
    return response.arrayBuffer();
  }

  function runWithFS(Module) {
    for (var dir of dirs) Module['FS_createPath'](dir[0], dir[1], true, true);
    Module['addRunDependency'](dependency);
    fetchPackage().then((buffer) => {
      var bytes = new Uint8Array(buffer);
      for (var file of files) Module['FS_createDataFile'](file.filename, null, bytes.subarray(file.start, file.end), true, true, true);
      Module['removeRunDependency'](dependency);
    });
  }

  if (Module['calledRun']) {
    runWithFS(Module);
  } else {
    if (!Module['preRun']) Module['preRun'] = [];
    Module['preRun'].push(runWithFS);
  }
})();
`;
}

async function coverageJobs(jobsPath) {
  const bundle = await build({
    entryPoints: [path.join(root, "scripts/coverage-cvs.ts")],
    bundle: true,
    format: "esm",
    platform: "node",
    write: false,
    logLevel: "error"
  });
  const { coverageCvs } = await import(`data:text/javascript;base64,${Buffer.from(bundle.outputFiles[0].text).toString("base64")}`);
  const files = [
    ...listFiles(texmfDir, false).map((file) => ({ path: path.basename(file), source: file })),
    ...listFiles(fontsDir, true).map((file) => ({ path: `Fonts/${path.relative(fontsDir, file).split(path.sep).join("/")}`, source: file }))
  ];
  writeFileSync(jobsPath, JSON.stringify({ cvs: coverageCvs(), files }));
}

function pack(publicPath, contents) {
  const compressed = gzipSync(contents, { level: zlibConstants.Z_BEST_COMPRESSION });
  const parts = [];
  for (let offset = 0; offset < compressed.length; offset += partSizeBytes) {
    const part = compressed.subarray(offset, offset + partSizeBytes);
    // Named by the part's own hash: parts are cached as immutable, by the browser and by the app between visits.
    const partHash = createHash("sha256").update(part).digest("hex").slice(0, 16);
    const name = `${path.posix.basename(publicPath)}.${partHash}.bin`;
    writeFileSync(path.join(packDir, name), part);
    parts.push({ url: `/core/packs/${name}`, size: part.length });
  }
  console.log(`packed ${publicPath}: ${mib(contents.length)} -> ${mib(compressed.length)}`);
  return parts;
}

for (const file of [...engineFiles, "texlive-basic.js", "texlive-basic.data"]) {
  if (!existsSync(path.join(vendorDir, file))) throw new Error(`Missing vendor/busytex/${file}: run npm run assets:download.`);
}
for (const file of requiredSupplementalAssets) {
  const filePath = path.join(texmfDir, file);
  if (!existsSync(filePath) || statSync(filePath).size === 0) throw new Error(`Missing supplemental TeX file ${filePath}`);
}

rmSync(busytexDir, { recursive: true, force: true });
mkdirSync(busytexDir, { recursive: true });
for (const file of engineFiles) copyFileSync(path.join(vendorDir, file), path.join(busytexDir, file));
appendFileSync(path.join(busytexDir, "busytex_pipeline.js"), `\n${readFileSync(path.join(root, "scripts/busytex-close-streams.js"), "utf8")}`);

// Trim the TeX Live package, then check the result against the full package's PDFs.
const work = mkdtempSync(path.join(tmpdir(), "cv-forge-assets-"));
try {
  const jobsPath = path.join(work, "jobs.json");
  await coverageJobs(jobsPath);
  const fullPackage = path.join(vendorDir, "texlive-basic.js");
  console.log("tracing the TeX Live files the template needs…");
  const tracedData = path.join(work, "traced.data");
  const traced = runEngine("trace", vendorDir, fullPackage, jobsPath, path.join(work, "trace.json"), tracedData);
  const tracedBytes = readFileSync(tracedData);
  const contents = new Map(traced.files.map((file) => [file.filename, tracedBytes.subarray(file.start, file.end)]));

  const fullLoader = readFileSync(fullPackage, "utf8");
  const providesComments = fullLoader
    .split("\n")
    .filter((line) => line.startsWith("//"))
    .join("\n");
  const dirs = [...fullLoader.matchAll(/FS_createPath'\]\("([^"]*)", "([^"]*)"/g)].map((match) => [match[1], match[2]]);
  const trimmedPackage = path.join(busytexDir, "texlive-basic.js");
  const trimmedData = path.join(busytexDir, "texlive-basic.data");

  /** Writes the package and returns the CVs whose PDFs differ from the full package's, with the engine's errors. */
  const writeAndVerify = (files) => {
    const entries = [];
    let offset = 0;
    for (const [filename, bytes] of files) {
      entries.push({ filename, start: offset, end: offset + bytes.length });
      offset += bytes.length;
    }
    writeFileSync(trimmedData, Buffer.concat([...files.values()]));
    writeFileSync(trimmedPackage, packageLoader(dirs, entries, providesComments));
    const hashes = runEngine("hashes", busytexDir, trimmedPackage, jobsPath, path.join(work, "hashes.json"));
    const changed = Object.keys(traced.hashes).filter((name) => hashes[name] !== traced.hashes[name]);
    return { changed, error: hashes.error };
  };

  const shrunkIcu = shrinkIcuData(contents, writeAndVerify);
  if (!shrunkIcu) {
    const { changed, error } = writeAndVerify(contents);
    if (changed.length) throw new Error(`The trimmed TeX Live package changes the PDF of: ${changed.join(", ")}\n${error ?? ""}`);
  }
  const fullSize = statSync(path.join(vendorDir, "texlive-basic.data")).size;
  const trimmedSize = statSync(trimmedData).size;
  console.log(
    `TeX Live package: ${traced.files.length} files, ${mib(trimmedSize)} (BusyTeX's: ${mib(fullSize)} LZ4); ${Object.keys(traced.hashes).length} CVs compile identically`
  );

  /**
   * XeTeX needs ICU's data only for its converter tables, so the 21 MiB bundle is cut down with icupkg (from ICU,
   * e.g. Homebrew's icu4c) to the smallest candidate that still compiles every CV identically.
   */
  function shrinkIcuData(files, verify) {
    const icuPath = [...files.keys()].find((filename) => /\/icudt\d+l\.dat$/.test(filename));
    const icupkg = findIcupkg();
    if (!icuPath) return false;
    if (!icupkg) {
      console.warn("icupkg not found (install ICU, e.g. brew install icu4c): keeping all of ICU's data");
      return false;
    }
    // icupkg wants the file named after the package inside it, so input and output live in separate directories.
    mkdirSync(path.join(work, "icu-in"));
    mkdirSync(path.join(work, "icu-out"));
    const fullIcu = path.join(work, "icu-in", path.posix.basename(icuPath));
    writeFileSync(fullIcu, files.get(icuPath));
    const items = execFileSync(icupkg, ["-l", fullIcu], { encoding: "utf8" }).split("\n").filter(Boolean);
    const candidates = [
      ["the converter alias table", /^cnvalias\.icu$/],
      ["Mac converters", /^(cnvalias\.icu|macos-.*\.cnv)$/],
      ["all converters", /^(cnvalias\.icu|.*\.cnv)$/]
    ];
    for (const [label, keep] of candidates) {
      const removeList = path.join(work, "icu-remove.txt");
      writeFileSync(removeList, items.filter((item) => !keep.test(item)).join("\n"));
      const reduced = path.join(work, "icu-out", path.posix.basename(icuPath));
      rmSync(reduced, { force: true });
      execFileSync(icupkg, ["--ignore-deps", "-r", removeList, fullIcu, reduced], { stdio: "ignore" });
      const trial = new Map(files);
      trial.set(icuPath, readFileSync(reduced));
      if (verify(trial).changed.length === 0) {
        console.log(`ICU data: kept ${label}, ${mib(trial.get(icuPath).length)} instead of ${mib(files.get(icuPath).length)}`);
        return true;
      }
    }
    return false;
  }
} finally {
  rmSync(work, { recursive: true, force: true });
}

rmSync(packDir, { recursive: true, force: true });
mkdirSync(packDir, { recursive: true });

const files = {};
const sources = [...listFiles(busytexDir, false), ...listFiles(texmfDir, false), ...listFiles(fontsDir, true)];
for (const filePath of sources.sort()) {
  const publicPath = toPublicPath(filePath);
  const contents = readFileSync(filePath);
  const entry = { size: contents.length, hash: createHash("sha256").update(contents).digest("hex").slice(0, 12) };
  if (packedExtensions.has(path.extname(filePath)) && contents.length > packThresholdBytes) {
    entry.parts = pack(publicPath, contents);
    // Only the parts can be deployed.
    if (contents.length > maxAssetBytes) rmSync(filePath);
  }
  files[publicPath] = entry;
}

writeFileSync(manifestPath, `${JSON.stringify({ files }, null, 2)}\n`);
console.log(`wrote ${toPublicPath(manifestPath)}: ${Object.keys(files).length} files`);
